package render

import (
	"fmt"
	"html"
	"io"
	"regexp"
	"strings"

	"github.com/Fahnoee/flakelog/internal/lock"
	"github.com/Fahnoee/flakelog/internal/report"
)

// MarkdownOptions controls Markdown output.
type MarkdownOptions struct {
	// Notable is how many notable commits to list per input.
	Notable int
	// Heading is the title line; empty means a generated one.
	Heading string
}

// Markdown writes a report suitable for a pull request body or comment.
func Markdown(w io.Writer, r *report.Report, opts MarkdownOptions) {
	heading := opts.Heading
	if heading == "" {
		heading = "flake.lock: " + countsLine(r)
	}
	fmt.Fprintf(w, "### %s\n\n", heading)

	var direct, transitive []*report.Entry
	for _, e := range r.Entries {
		if e.Direct() {
			direct = append(direct, e)
		} else {
			transitive = append(transitive, e)
		}
	}
	if len(r.Entries) == 0 && r.HiddenTransitive == 0 {
		fmt.Fprintln(w, "No inputs changed.")
	}
	if len(direct) > 0 {
		mdTable(w, direct)
		mdNotable(w, direct, opts)
	}
	if len(transitive) > 0 {
		fmt.Fprintf(w, "<details><summary>%s of inputs changed</summary>\n\n", plural(len(transitive), "input"))
		mdTable(w, transitive)
		fmt.Fprint(w, "</details>\n\n")
	} else if r.HiddenTransitive > 0 {
		fmt.Fprintf(w, "_Also changed: %s of inputs (run with `--all` to list them)._\n\n", plural(r.HiddenTransitive, "input"))
	}
	for _, warn := range r.Warnings {
		fmt.Fprintf(w, "> [!WARNING]\n> %s\n\n", warn)
	}
	fmt.Fprintln(w, "<sub>Generated by [flakelog](https://github.com/Fahnoee/flakelog)</sub>")
}

func mdTable(w io.Writer, entries []*report.Entry) {
	fmt.Fprintln(w, "| Input | Change | Commits | Jump | Notable |")
	fmt.Fprintln(w, "|---|---|---|---|---|")
	for _, e := range entries {
		var change, commits, notable string
		switch e.Kind {
		case lock.Added:
			change = "added " + code(sourceLabel(e.New))
		case lock.Removed:
			change = "removed " + code(sourceLabel(e.Old))
		case lock.Retargeted:
			change = code(sourceLabel(e.Old)) + " → " + code(sourceLabel(e.New))
		case lock.Updated:
			change = code(revLabel(e.Old.Locked)) + " → " + code(revLabel(e.New.Locked))
			if e.CompareURL != "" {
				change = "[" + change + "](" + e.CompareURL + ")"
			}
			commits = commitsLabel(e.Range)
			notable = tagSummary(e.Range)
			if e.RangeError != "" {
				notable = "_unavailable_"
			}
		default:
			panic(fmt.Sprintf("unhandled change kind %q", e.Kind))
		}
		fmt.Fprintf(w, "| **%s** | %s | %s | %s | %s |\n", escape(e.Path), change, commits, jumpLabel(e), notable)
	}
	fmt.Fprintln(w)
}

func mdNotable(w io.Writer, entries []*report.Entry, opts MarkdownOptions) {
	for _, e := range entries {
		if e.Range == nil || len(e.Range.Notable) == 0 {
			continue
		}
		repo := ""
		if s := e.New.Locked; s != nil && s.Type == "github" {
			repo = s.Owner + "/" + s.Repo
		}
		summary := fmt.Sprintf("<b>%s</b>: %s", html.EscapeString(e.Path), plural(len(e.Range.Notable), "notable commit"))
		if n := scannedNote(e.Range); n != "" {
			summary += " (" + n + ")"
		}
		fmt.Fprintf(w, "<details><summary>%s</summary>\n\n", summary)
		for i, c := range e.Range.Notable {
			if i == opts.Notable {
				fmt.Fprintf(w, "- … and %d more\n", len(e.Range.Notable)-i)
				break
			}
			sha := code(shortRev(c.SHA))
			if c.URL != "" {
				sha = "[" + sha + "](" + c.URL + ")"
			}
			title := commitTitle(c.Title, repo)
			if ids := bodyAdvisories(c); len(ids) > 0 {
				title += " · mentions " + strings.Join(ids, ", ")
			}
			fmt.Fprintf(w, "- **%s** %s (%s)\n", c.Tags[0], title, sha)
		}
		fmt.Fprint(w, "\n</details>\n\n")
	}
}

func code(s string) string {
	if s == "" {
		return ""
	}
	return "`" + strings.ReplaceAll(s, "`", "'") + "`"
}

var (
	mdSpecial = regexp.MustCompile("[\\\\`*_\\[\\]<|~]")
	// GitHub autolinks references after any non-word character.
	issueRef = regexp.MustCompile(`(^|[^\w])#(\d+)\b`)
	mention  = regexp.MustCompile(`(^|[^\w])@([A-Za-z0-9][A-Za-z0-9-]*(?:/[A-Za-z0-9_.-]+)?)`)
)

func escape(s string) string {
	return mdSpecial.ReplaceAllString(s, `\$0`)
}

// commitTitle escapes a commit title for a PR body in another repo. A bare
// "#123" would link this repo's issue, "owner/repo#123" would post a backlink
// on the upstream PR from every downstream PR, and "@user" would ping strangers.
// Links via redirect.github.com, like Renovate's, create no backlink.
func commitTitle(title, repo string) string {
	s := escape(title)
	if repo != "" {
		s = issueRef.ReplaceAllString(s, "${1}[#${2}](https://redirect.github.com/"+repo+"/issues/${2})")
	} else {
		s = issueRef.ReplaceAllString(s, "${1}`#${2}`")
	}
	return mention.ReplaceAllString(s, "${1}`@${2}`")
}
